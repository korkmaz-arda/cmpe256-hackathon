"""Text extraction from the course PDFs and saved web pages.

PDFs: one text string per physical page (1-based page numbers are what citations show).
HTML: the saved pages contain the full site template (mega-menus, cookie banners, footers).
We remove it in a site-agnostic way: any line that also appears on another saved page of the
same site is template, not content. Headings (h1-h4) are kept as "### " lines so chunks can be
cited by section.
"""
from __future__ import annotations

import re
import unicodedata
from collections import Counter
from pathlib import Path

import pymupdf
from bs4 import BeautifulSoup

_BOILERPLATE = re.compile(
    r"(cookie|sign in|sign out|log in|log out|session has expired|skip to (main content|search|footer)|"
    r"accept all|reject all|privacy (statement|preference)|rate your experience|results generated by ai|"
    r"how can i help\?|expand the window|stay organized with collections|save and categorize content)",
    re.I,
)


def normalize(text: str) -> str:
    text = unicodedata.normalize("NFKC", text).replace("​", "")
    text = re.sub(r"[ \t ]+", " ", text)
    return re.sub(r"\n\s*\n+", "\n\n", text).strip()


def pdf_pages(path: Path) -> list[str]:
    with pymupdf.open(path) as doc:
        return [normalize(page.get_text()) for page in doc]


def _html_lines(path: Path) -> list[str]:
    soup = BeautifulSoup(path.read_text(encoding="utf-8", errors="ignore"), "html.parser")
    for tag in soup(["script", "style", "noscript", "svg", "template", "iframe"]):
        tag.decompose()
    # inline markup would otherwise split one sentence over several lines
    for tag in soup.find_all(["a", "span", "strong", "em", "b", "i", "code", "sup", "sub", "abbr", "u"]):
        tag.unwrap()
    soup.smooth()
    for h in soup.find_all(["h1", "h2", "h3", "h4"]):
        title = " ".join(h.get_text(" ").split())
        h.replace_with(f"\n### {title}\n" if title else "")
    lines = [" ".join(line.split()) for line in soup.get_text("\n").split("\n")]
    return [line for line in lines if len(line) > 2]


def _from_title_heading(lines: list[str]) -> list[str]:
    """Pages whose template no sibling shares (e.g. a newsroom article) still carry their menus.
    If a heading repeats the page <title>, the article starts there: keep the title line and
    everything from that heading on."""
    if not lines:
        return lines
    core = re.split(r" [|\-–] ", lines[0])[0].strip().casefold()
    for i, line in enumerate(lines[1:], start=1):
        if line.startswith("### ") and core and line[4:].casefold().startswith(core[:40]):
            return [lines[0]] + lines[i + 1:]  # the heading repeats the title line
    return lines


_TAIL_HEADING = re.compile(
    r"^### (what's next|newsroom highlights|related (products|content|news)|products and pricing|"
    r"take the next step|continue browsing|customers also viewed|your session has expired|privacy preference center)",
    re.I,
)


def _until_page_tail(lines: list[str]) -> list[str]:
    """Cut the page at the first 'what's next / related / footer' heading."""
    for i, line in enumerate(lines):
        if i > 1 and _TAIL_HEADING.match(line):
            return lines[:i]
    return lines


def html_documents(paths: list[Path]) -> dict[Path, str]:
    """Clean a group of pages saved from the same site; returns path -> cleaned text."""
    per_page = {p: _until_page_tail(_from_title_heading(_html_lines(p))) for p in paths}
    seen_on = Counter(line for lines in per_page.values() for line in set(lines))
    multi_page = len(paths) > 1
    out: dict[Path, str] = {}
    for p, lines in per_page.items():
        kept, last = [], None
        for line in lines:
            if multi_page and seen_on[line] > 1 and not line.startswith("### "):
                continue  # site template (menus, footers) shared with sibling pages
            if _BOILERPLATE.search(line) or line == last:
                continue
            kept.append(line)
            last = line
        # drop headings left without any body text
        cleaned = [l for i, l in enumerate(kept)
                   if not (l.startswith("### ") and (i + 1 == len(kept) or kept[i + 1].startswith("### ")))]
        out[p] = normalize("\n".join(cleaned))
    return out
