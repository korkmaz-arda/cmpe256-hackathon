"""Generate docs/AGENTS.md from the live code: personas, grounding sources, gaps, tools and full prompts.

    python scripts/gen_agent_cards.py

Because the cards are generated from the same objects the agents run with, the documentation cannot drift
from what the code does (tests/test_grounding.py checks the prompts against the source manifest).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from consultai.agents.registry import specialists  # noqa: E402
from consultai.config import INDEX_DIR, model_profile  # noqa: E402
from consultai.contracts import EVIDENCE_PREFIX  # noqa: E402
from consultai.ingest.sources import KNOWN_GAPS, sources_for  # noqa: E402
from consultai.orchestrator.router import router_system_prompt  # noqa: E402


def chunk_counts() -> dict:
    out = {}
    for d in INDEX_DIR.iterdir() if INDEX_DIR.exists() else []:
        f = d / "info.json"
        if f.exists():
            out.update(json.loads(f.read_text()).get("chunks_per_source", {}))
    return out


def main() -> None:
    demo, dev = model_profile("demo"), model_profile("dev")
    counts = chunk_counts()
    md = ["# Agent cards", "",
          "_Generated by `python scripts/gen_agent_cards.py` from the running code: the grounding lists come from "
          "`consultai/ingest/sources.py`, the tool lists from each agent's real tools, the prompts are exactly what is "
          "sent to Claude._", "",
          f"Models: router **{demo.router}**; specialists **{demo.specialist}** (`demo`) / **{dev.specialist}** (`dev`); "
          f"review and synthesis **{demo.synthesis}** (see `config/models.yaml`).", "",
          "## Management Consulting Manager Agent (Engagement Manager)", "",
          "Responsibilities: intent detection and routing (small model), task framing, dependency-aware parallel "
          "dispatch, progress review with at most one follow-up round, synthesis, citation verification. Prompts: "
          "`consultai/agents/manager/{router,review,synthesis}_prompt.md`.", "",
          "<details><summary>Router prompt as sent (with generated capability cards)</summary>", "",
          router_system_prompt(), "", "</details>", ""]
    for name, a in specialists().items():
        md += [f"## {a.display_name} - {a.persona}", "", a.capability, "",
               f"Evidence ids: `{EVIDENCE_PREFIX[name]}-n` · prompt file: `consultai/agents/{name}/prompt.md` + "
               f"`consultai/agents/common_policy.md`", "", "**Grounding sources**", "",
               "| source_id | title | collection | chunks | URL |", "|---|---|---|---|---|"]
        for s in sources_for(name):
            md.append(f"| `{s.source_id}` | {s.title} | {s.collection} | {counts.get(s.source_id, '-')} | {s.citation_url or '(course file)'} |")
        md += ["", "**Known gaps**", ""] + [f"- {g}" for g in KNOWN_GAPS[name]]
        md += ["", "**Tools**", ""] + [f"- `{n}`: {d}" for n, d in a.tool_specs()]
        md += ["", "<details><summary>Full system prompt as sent</summary>", "", a.system_prompt(), "", "</details>", ""]
    out = ROOT / "docs" / "AGENTS.md"
    out.write_text("\n".join(md))
    print(f"wrote {out} ({len(md)} lines)")


if __name__ == "__main__":
    main()
